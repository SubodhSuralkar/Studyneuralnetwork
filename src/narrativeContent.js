// ── HELPER: Get narrative entry by chapter number ──────────────────
export function getNarrativeByChapter(chapterNumber) {
  return ECHO_NARRATIVE.find(n => n.chapter === chapterNumber) || null;
}

// ── HELPER: Map completed chapter key → narrative chapter index ────
// The 21 chapters map in order of the SYLLABUS flattened array.
export function getChapterIndexFromKey(chapterKey, syllabusFlat) {
  const idx = syllabusFlat.findIndex(
    ch => `${ch.subject}::${ch.name}` === chapterKey
  );
  return idx >= 0 ? idx + 1 : null; // 1-indexed
}

// Signal color helper
export function getSignalColor(signal) {
  if (signal >= 75) return '#00ff41';
  if (signal >= 50) return '#ffff00';
  if (signal >= 25) return '#ff6b00';
  return '#ff0000';
}
